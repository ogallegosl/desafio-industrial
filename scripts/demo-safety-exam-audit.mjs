import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8')
const exists = (p) => fs.existsSync(path.join(root, p))
const checks = []
const check = (name, ok) => checks.push({ name, ok: Boolean(ok) })

const migration = read('supabase/migrations/0022_safety_demo_exam.sql')
const edge = read('supabase/functions/exam-access/index.ts')
const examsPage = read('src/pages/TeacherExamsPage.jsx')
const demoService = read('src/services/demoData.js')
const qService = read('src/services/questionBankManagement.js')
const bootstrap = read('supabase/sql/bootstrap_all.sql')

check('Migration 0022 exists', exists('supabase/migrations/0022_safety_demo_exam.sql'))
check('Demo SVG exists', exists('public/demo/seguridad-almacen.svg'))
check('Authenticated demo RPC exists', /create or replace function public\.create_safety_demo\(\)/.test(migration))
check('Anonymous execution revoked', /revoke all on function public\.create_safety_demo\(\) from public, anon/.test(migration))
check('Authenticated execution granted', /grant execute on function public\.create_safety_demo\(\) to authenticated/.test(migration))
check('Active teacher required', /private\.current_teacher_id\(\)/.test(migration) && /ACTIVE_TEACHER_REQUIRED/.test(migration))
check('Demo is idempotent', /if v_exam_id is not null then/.test(migration) && /'created', false/.test(migration))
check('Demo records are labeled', /\[DEMO\]/.test(migration) && /DEMO_DATA_PROMPT16/.test(migration))
check('Target is exactly 15 top-level questions', /target_question_count = 15/.test(migration) && /v_count <> 15/.test(migration))
check('Single choice included', /'single_choice'/.test(migration))
check('Multiple choice included', /'multiple_choice'/.test(migration))
check('True false included', /'true_false'/.test(migration))
check('Short text included', /'short_text'/.test(migration))
check('Numeric included', /'numeric'/.test(migration))
check('Essay included', /'essay'/.test(migration))
check('Image choice included', /'image_single_choice'/.test(migration))
check('Image essay included', /'image_essay'/.test(migration))
check('Calculation included', /'calculation'/.test(migration))
check('Calculation evidence included', /'calculation_evidence'/.test(migration))
check('Attachment included', /'attachment'/.test(migration))
check('Case group included', /'case_group'/.test(migration))
check('Demo image URL is stored in metadata', /demoMediaUrl.*seguridad-almacen\.svg/.test(migration))
check('Student payload resolves demo media without exposing grading', /demoMediaUrl/.test(edge) && /const mediaUrl = signedUrl \|\| demoMediaUrl/.test(edge))
check('Question editor preserves demo metadata', /const metadata = \{ \.\.\.\(question\.metadata \|\| \{\}\), editorVersion: 1 \}/.test(qService))
check('Replacing/removing image clears demo fallback', /delete metadata\.demoMediaUrl/.test(qService))
check('Teacher page exposes one-click demo creation', /Crear examen DEMO/.test(examsPage) && /createSafetyDemo/.test(examsPage))
check('Frontend service calls demo RPC', /rpc\(['"]create_safety_demo['"]\)/.test(demoService))
check('Exam randomizes questions and options', /randomize_questions = true/.test(migration) && /randomize_options = true/.test(migration))
check('Exam uses 45-minute runtime', /duration_minutes = 45/.test(migration))
check('Exam access code is hashed', /extensions\.digest\(v_code/.test(migration) && /extensions\.crypt\(v_code/.test(migration))
check('Bootstrap contains migration 0022', /0022_safety_demo_exam\.sql|Prompt 16: idempotent demo/.test(bootstrap))

const linkedQuestions = (migration.match(/insert into public\.preguntas_examen\(exam_id,question_id,fixed_position\)/g) || []).length
check('Fifteen top-level question links are declared', linkedQuestions === 15)

const failed = checks.filter((c) => !c.ok)
for (const c of checks) console.log(`${c.ok ? 'PASS' : 'FAIL'} - ${c.name}`)
console.log(`\nPrompt 16 demo audit: ${checks.length - failed.length}/${checks.length} PASS`)
if (failed.length) process.exit(1)
